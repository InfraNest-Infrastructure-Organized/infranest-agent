// Listening is what this machine accepts connections on (InfraNest #4019), read from the kernel's socket
// tables in /proc/net. A snapshot like `services`: it describes now, and rides on the newest sample only.
//
// It exists so the server can compare a firewall's open ports with what actually listens behind them —
// "port 8080 is open and nothing listens", or "a database listens on every address" — which the firewall
// rules alone cannot say.
//
// Two things are deliberately not here:
//
//   - **No remote addresses it was not given.** The peers of a connection are this customer's own clients,
//     which is personal data the receiver has no use for. Only counts by class leave the machine; the
//     addresses are classified in memory and dropped. The one exception is `known_peers` (InfraNest #4903):
//     connections to and from the addresses InfraNest itself sent in the push response, which are the same
//     organization's other servers. Those addresses came from the receiver, so reporting them back tells it
//     nothing about anyone else.
//   - **No program names.** Tying a socket to its process means reading /proc/<pid>/fd, which an
//     unprivileged agent can do only for its own processes. A name reported for some ports and not others
//     would read as complete when it is not, so none is reported, and the receiver must never show one it
//     did not observe.
type Listening struct {
	// One entry per protocol and port, ranked — see rankListening — and capped at maxListeningPorts. Never
	// nil once collected: `[]` is "nothing listens", which must reach the receiver as such.
	Ports []ListeningPort `json:"ports"`
	// Entries collected but not sent because of the cap. Sent always, so a truncated list cannot pass for
	// a complete one.
	More int `json:"more"`
	// A socket table was longer than the agent reads (maxSocketRows). The kernel lists listening TCP
	// sockets before connected ones, so the ports are complete and the peer counts are lower bounds; for
	// UDP, which has one list, ports may be missing too.
	Partial bool `json:"partial"`
	// Established TCP connections to and from the addresses InfraNest named (InfraNest #4903), by address,
	// port and direction. Absent when the agent holds no list — an older receiver, or the first reading after
	// a restart — and `[]` when it has one and nothing on it is connected: the two mean different things.
	KnownPeers *[]KnownPeer `json:"known_peers,omitempty"`
}

// KnownPeer is one of this organization's servers that this machine is connected to.
type KnownPeer struct {
	Address string `json:"address"`
	// The port that identifies the service: ours for "in" (the peer connects to a port we listen on), theirs
	// for "out" (we connect to a port the peer listens on). The other side's ephemeral port says nothing.
	Port      int    `json:"port"`
	Direction string `json:"direction"` // "in" or "out"
	// Established connections right now. A pool of twenty to one database is twenty.
	Connections int `json:"connections"`
}

// ListeningPort is one protocol and port, with every local address it is bound to.
type ListeningPort struct {
	Protocol string `json:"protocol"` // "tcp" or "udp"
	Port     int    `json:"port"`
	// The widest of its binds: "all" (0.0.0.0 or ::), "specific" (one of this machine's addresses), or
	// "loopback" (127.0.0.0/8 or ::1 only).
	Bind string `json:"bind"`
	// The local addresses, wildcards first, at most maxListeningAddresses. These are this machine's own
	// addresses, never a peer's.
	Addresses []string `json:"addresses"`
	// Distinct remote addresses with an established connection to this port, by class — counts only.
	// TCP only: UDP has no connections to count.
	Peers *PeerCounts `json:"peers,omitempty"`
}

// PeerCounts is how many distinct remote addresses are connected to a port, by where they are. The
// addresses themselves are never sent.
type PeerCounts struct {
	Loopback int `json:"loopback"`
	// RFC 1918, RFC 4193 (fc00::/7), CGNAT (100.64.0.0/10) and link-local.
	Private int `json:"private"`
	Public  int `json:"public"`
}

const (
	// A busy reverse proxy has a few dozen; a box with more than this is reporting something unusual, and
	// the rest is counted in `more`.
	maxListeningPorts = 100
	// Per port. More than this many specific addresses on one port is rare enough that `bind` — computed
	// over all of them — says what matters.
	maxListeningAddresses = 8
	// Rows read per socket table. /proc/net/tcp on a machine with a million connections is a hundred
	// megabytes generated by the kernel on every read, under a 5% CPU quota; stopping here costs only
	// peer counts, because listeners are listed first.
	maxSocketRows = 100_000
	// Distinct (port, peer) pairs held while counting. Bounds memory under the unit's 64M ceiling.
	maxPeerPairs = 65_536
	// Known-peer edges sent. A server talking to more of its own fleet than this on distinct ports is
	// unusual; the list is ranked by connections first, so the cap drops the least used.
	maxKnownPeers = 200
	// Addresses accepted from the receiver. Bounds the set held between samples.
	MaxKnownPeerAddresses = 4096
)

// Kernel socket states, as /proc/net/{tcp,udp}* print them (include/net/tcp_states.h).
const (
	stateEstablished = "01"
	stateClose       = "07" // for UDP: bound, not connected
	stateListen      = "0A"
)

const (
	bindLoopback = "loopback"
	bindSpecific = "specific"
	bindAll      = "all"
)

// errSocketTableFormat is a header or row the parser does not recognise. A table we cannot read is a
// failed collector, never an empty answer: "nothing listens" is a claim the receiver acts on.
var errSocketTableFormat = errors.New("unrecognised socket table format")

type portKey struct {
	proto string
	port  uint16
}

type peerKey struct {
	port uint16
	addr netip.Addr
}

// listenAccumulator gathers listeners and TCP peers across the four tables, then turns them into the
// payload. It never holds more than maxPeerPairs peer entries.
type edgeKey struct {
	addr netip.Addr
	port uint16
	dir  string
}

type listenAccumulator struct {
	ports   map[portKey]map[netip.Addr]struct{}
	peers   map[peerKey]struct{}
	partial bool
	// nil when the agent holds no list from the receiver; edges is then never filled or sent.
	known map[netip.Addr]struct{}
	edges map[edgeKey]int
}

func newListenAccumulator(known map[netip.Addr]struct{}) *listenAccumulator {
	return &listenAccumulator{
		ports: map[portKey]map[netip.Addr]struct{}{},
		peers: map[peerKey]struct{}{},
		known: known,
		edges: map[edgeKey]int{},
	}
}

// edge counts one established connection with a known peer. Incoming when the local port is one we
// listen on; outgoing otherwise, keyed by the peer's port. Bounded like the peer pairs.
func (a *listenAccumulator) edge(row socketRow) {
	if a.known == nil {
		return
	}
	if _, ok := a.known[row.remote]; !ok {
		return
	}
	k := edgeKey{addr: row.remote, port: row.remotePort, dir: "out"}
	if _, listening := a.ports[portKey{"tcp", row.localPort}]; listening {
		k = edgeKey{addr: row.remote, port: row.localPort, dir: "in"}
	}
	if _, ok := a.edges[k]; !ok && len(a.edges) >= maxPeerPairs {
		a.partial = true
		return
	}
	a.edges[k]++
}

func (a *listenAccumulator) listen(proto string, addr netip.Addr, port uint16) {
	k := portKey{proto, port}
	if a.ports[k] == nil {
		a.ports[k] = map[netip.Addr]struct{}{}
	}
	a.ports[k][addr] = struct{}{}
}

func (a *listenAccumulator) peer(port uint16, remote netip.Addr) {
	k := peerKey{port, remote}
	if _, ok := a.peers[k]; ok {
		return
	}
	if len(a.peers) >= maxPeerPairs {
		a.partial = true
		return
	}
	a.peers[k] = struct{}{}
}

// socketRow is the three columns we read from one line: local address and port, remote address, state.
type socketRow struct {
	local      netip.Addr
	localPort  uint16
	remote     netip.Addr
	state      string
	remotePort uint16
}

// parseSocketRow reads one data line of /proc/net/{tcp,tcp6,udp,udp6}:
//
//	sl  local_address rem_address   st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode
//	 0: 0100007F:0CEA 00000000:0000 0A 00000000:00000000 00:00000000 00000000   999        0 21414 1 …
//
// order is the byte order of the machine that wrote it — see decodeProcAddr.
func parseSocketRow(line string, order binary.ByteOrder) (socketRow, error) {
	f := strings.Fields(line)
	if len(f) < 4 || !strings.HasSuffix(f[0], ":") {
		return socketRow{}, errSocketTableFormat
	}

	local, lport, err := decodeProcEndpoint(f[1], order)
	if err != nil {
		return socketRow{}, err
	}
	remote, rport, err := decodeProcEndpoint(f[2], order)
	if err != nil {
		return socketRow{}, err
	}
	if len(f[3]) != 2 {
		return socketRow{}, errSocketTableFormat
	}

	return socketRow{local: local, localPort: lport, remote: remote, remotePort: rport, state: strings.ToUpper(f[3])}, nil
}

func decodeProcEndpoint(s string, order binary.ByteOrder) (netip.Addr, uint16, error) {
	addrHex, portHex, ok := strings.Cut(s, ":")
	if !ok || len(portHex) != 4 {
		return netip.Addr{}, 0, errSocketTableFormat
	}
	addr, err := decodeProcAddr(addrHex, order)
	if err != nil {
		return netip.Addr{}, 0, err
	}
	port, err := strconv.ParseUint(portHex, 16, 16)
	if err != nil {
		return netip.Addr{}, 0, errSocketTableFormat
	}

	return addr, uint16(port), nil
}

// decodeProcAddr turns the kernel's hex address into an address.
//
// The kernel prints an IPv4 address as the 32-bit word it is stored in, with %08X — so the bytes come
// out in the *host's* order: 127.0.0.1 is 0100007F on x86 and arm64, and 7F000001 on s390x. An IPv6
// address is four such words. Each word is therefore read as a number and written back in the host's
// byte order to recover the address's own bytes. The port is printed after ntohs and needs no such care.
//
// An IPv4-mapped IPv6 address (::ffff:a.b.c.d — an IPv4 client of a dual-stack socket) is unmapped, so
// one peer or one bind is one address however it reached us.
func decodeProcAddr(s string, order binary.ByteOrder) (netip.Addr, error) {
	if len(s) != 8 && len(s) != 32 {
		return netip.Addr{}, errSocketTableFormat
	}
	raw, err := hex.DecodeString(s)
	if err != nil {
		return netip.Addr{}, errSocketTableFormat
	}

	b := make([]byte, len(raw))
	for i := 0; i < len(raw); i += 4 {
		order.PutUint32(b[i:], binary.BigEndian.Uint32(raw[i:]))
	}

	if len(b) == 4 {
		return netip.AddrFrom4([4]byte(b)), nil
	}

	return netip.AddrFrom16([16]byte(b)).Unmap(), nil
}

// scanSocketTable reads one table into acc. proto is "tcp" or "udp".
//
// TCP: LISTEN rows are listeners, and ESTABLISHED rows whose local port is a listener's are peers of that
// port. With listenersOnly, it returns at the first row that is not a listener — the kernel walks its
// listening hash before its established one, so that is where they end. The caller does that pass over
// both tables first, so a connection in one table to a listener in the other is still counted: see
// collectListening.
//
// UDP: a bound socket with no connected peer (state CLOSE, remote 0) is a listener; a connected one is a
// client and is skipped.
func scanSocketTable(r io.Reader, proto string, order binary.ByteOrder, acc *listenAccumulator, listenersOnly bool) error {
	sc := bufio.NewScanner(r)
	rows := 0

	if !sc.Scan() {
		if err := sc.Err(); err != nil {
			return err
		}
		return errSocketTableFormat // not even a header
	}
	if !strings.HasPrefix(strings.TrimSpace(sc.Text()), "sl") {
		return errSocketTableFormat
	}

	for sc.Scan() {
		rows++
		if rows > maxSocketRows {
			acc.partial = true
			return nil
		}

		row, err := parseSocketRow(sc.Text(), order)
		if err != nil {
			return err
		}

		if listenersOnly && row.state != stateListen {
			return nil
		}

		switch {
		case proto == "tcp" && row.state == stateListen:
			if row.localPort != 0 {
				acc.listen(proto, row.local, row.localPort)
			}
		case proto == "tcp" && row.state == stateEstablished:
			if _, ok := acc.ports[portKey{"tcp", row.localPort}]; ok {
				acc.peer(row.localPort, row.remote)
			}
			acc.edge(row)
		case proto == "udp" && row.state == stateClose && row.remote.IsUnspecified() && row.remotePort == 0:
			if row.localPort != 0 {
				acc.listen(proto, row.local, row.localPort)
			}
		}
	}

	return sc.Err()
}

// collectListening reads the four tables through open, which returns fs.ErrNotExist for a table this
// kernel does not have — tcp6 and udp6 on a kernel without IPv6. Only /proc/net/tcp is required: without
// it there is no answer, and the collector fails rather than reporting that nothing listens.
//
// The TCP tables are read twice: a first pass for listeners only, so that a connection in one table to a
// listener described in the other is still counted, then a full pass. The first pass stops at the first
// row that is not a listener, which on every kernel is where the listeners end, so it costs a few dozen
// lines. Nothing depends on that ordering for correctness: the full pass records listeners too, and on a
// kernel that interleaved them only the peers seen before their listener would be missed.
func collectListening(open func(name string) (io.ReadCloser, error), order binary.ByteOrder, known map[netip.Addr]struct{}) (*Listening, error) {
	acc := newListenAccumulator(known)

	read := func(name, proto string, required, listenersOnly bool) error {
		f, err := open(name)
		if err != nil {
			if !required && errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			return err
		}
		defer func() { _ = f.Close() }()

		return scanSocketTable(f, proto, order, acc, listenersOnly)
	}

	steps := []struct {
		name, proto             string
		required, listenersOnly bool
	}{
		{"tcp", "tcp", true, true},
		{"tcp6", "tcp", false, true},
		{"tcp", "tcp", true, false},
		{"tcp6", "tcp", false, false},
		{"udp", "udp", false, false},
		{"udp6", "udp", false, false},
	}
	for _, s := range steps {
		if err := read(s.name, s.proto, s.required, s.listenersOnly); err != nil {
			return nil, err
		}
	}

	return acc.result(), nil
}

// result builds the payload: one entry per protocol and port, ranked, capped, peers classified and the
// addresses dropped.
func (a *listenAccumulator) result() *Listening {
	counts := map[uint16]*PeerCounts{}
	for k := range a.peers {
		c := counts[k.port]
		if c == nil {
			c = &PeerCounts{}
			counts[k.port] = c
		}
		switch peerClass(k.addr) {
		case bindLoopback:
			c.Loopback++
		case "private":
			c.Private++
		default:
			c.Public++
		}
	}

	ports := make([]ListeningPort, 0, len(a.ports))
	for k, addrs := range a.ports {
		list := make([]netip.Addr, 0, len(addrs))
		for addr := range addrs {
			list = append(list, addr)
		}
		// Wildcards first, then IPv4 before IPv6, then numerically: the order a reader expects, and stable
		// between samples so the receiver does not see a change that is not one.
		slices.SortFunc(list, func(x, y netip.Addr) int {
			if c := cmp.Compare(bindRank(bindOf(x)), bindRank(bindOf(y))); c != 0 {
				return c
			}
			return x.Compare(y)
		})

		bind := bindLoopback
		for _, addr := range list {
			if bindRank(bindOf(addr)) < bindRank(bind) {
				bind = bindOf(addr)
			}
		}

		p := ListeningPort{Protocol: k.proto, Port: int(k.port), Bind: bind}
		for i, addr := range list {
			if i == maxListeningAddresses {
				break
			}
			p.Addresses = append(p.Addresses, addr.String())
		}
		if k.proto == "tcp" {
			p.Peers = &PeerCounts{}
			if c := counts[k.port]; c != nil {
				p.Peers = c
			}
		}
		ports = append(ports, p)
	}

	rankListening(ports)

	out := &Listening{Ports: ports, Partial: a.partial}
	if len(ports) > maxListeningPorts {
		out.Ports = ports[:maxListeningPorts]
		out.More = len(ports) - maxListeningPorts
	}

	if a.known != nil {
		peers := make([]KnownPeer, 0, len(a.edges))
		for k, n := range a.edges {
			peers = append(peers, KnownPeer{Address: k.addr.String(), Port: int(k.port), Direction: k.dir, Connections: n})
		}
		// Most connections first, then a stable order, so the cap drops the least used and the receiver sees
		// no change that is not one.
		slices.SortFunc(peers, func(x, y KnownPeer) int {
			if c := cmp.Compare(y.Connections, x.Connections); c != 0 {
				return c
			}
			if c := cmp.Compare(x.Address, y.Address); c != 0 {
				return c
			}
			if c := cmp.Compare(x.Direction, y.Direction); c != 0 {
				return c
			}
			return cmp.Compare(x.Port, y.Port)
		})
		if len(peers) > maxKnownPeers {
			peers = peers[:maxKnownPeers]
		}
		out.KnownPeers = &peers
	}

	return out
}

// KnownPeerSet turns the addresses the receiver sent into the set the collector matches against. Anything
// that does not parse is skipped; the set is capped. IPv4-mapped addresses are unmapped, as the socket
// tables' are, so one server is one address however it is written.
func KnownPeerSet(addresses []string) map[netip.Addr]struct{} {
	set := make(map[netip.Addr]struct{}, min(len(addresses), MaxKnownPeerAddresses))
	for _, s := range addresses {
		if len(set) >= MaxKnownPeerAddresses {
			break
		}
		if a, err := netip.ParseAddr(strings.TrimSpace(s)); err == nil && !a.IsUnspecified() && !a.IsLoopback() {
			set[a.Unmap()] = struct{}{}
		}
	}

	return set
}

// rankListening orders the exposed before the private: bound to every address, then to a specific one,
// then loopback only — so that what the cap drops, if it drops anything, is what nobody outside can
// reach. Then TCP before UDP, then by port.
func rankListening(ports []ListeningPort) {
	slices.SortFunc(ports, func(x, y ListeningPort) int {
		if c := cmp.Compare(bindRank(x.Bind), bindRank(y.Bind)); c != 0 {
			return c
		}
		if c := cmp.Compare(x.Protocol, y.Protocol); c != 0 {
			// "tcp" < "udp"
			return c
		}
		return cmp.Compare(x.Port, y.Port)
	})
}

func bindRank(bind string) int {
	switch bind {
	case bindAll:
		return 0
	case bindSpecific:
		return 1
	default:
		return 2
	}
}

func bindOf(addr netip.Addr) string {
	switch {
	case addr.IsUnspecified():
		return bindAll
	case addr.IsLoopback():
		return bindLoopback
	default:
		return bindSpecific
	}
}

// cgnat is RFC 6598's shared address space — Tailscale and carrier NAT — which is nobody's public address.
var cgnat = netip.MustParsePrefix("100.64.0.0/10")

// peerClass is where a remote address is: "loopback", "private" or "public". The address goes no further.
func peerClass(addr netip.Addr) string {
	switch {
	case addr.IsLoopback():
		return bindLoopback
	case addr.IsPrivate(), addr.IsLinkLocalUnicast(), cgnat.Contains(addr):
		return "private"
	default:
		return "public"
	}
}
